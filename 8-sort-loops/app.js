
// Исходный массив
const arr = [1, 40, -5, 10, 0];

/**
 * Сортирует массив по возрастанию с помощью алгоритма пузырьком.
 * @param {number[]} array - Массив чисел для сортировки.
 */
function bubbleSort(array) {
    const n = array.length;

    // Внешний цикл проходит по всем элементам
    for (let i = 0; i < n - 1; i++) {
        // Внутренний цикл сравнивает соседние элементы
        // После каждой итерации внешнего цикла самый большой элемент "всплывает" в конец
        for (let j = 0; j < n - 1 - i; j++) {
            // Если текущий элемент больше следующего, меняем их местами
            if (array[j] > array[j + 1]) {
                // Временная переменная для обмена
                let temp = array[j];
                array[j] = array[j + 1];
                array[j + 1] = temp;
            }
        }
    }
}

// Вызываем функцию сортировки
bubbleSort(arr);

// Выводим отсортированный массив в консоль
console.log(arr); // Результат: [-5, 0, 1, 10, 40]